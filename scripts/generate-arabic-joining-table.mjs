/** Unicode property preparation only, never contextual shaping.
 * Arabic CCC remap follows HarfBuzz 11.0.1 hb-unicode.hh (MIT, HarfBuzz authors).
 * MCM membership: Unicode UTR #53, https://www.unicode.org/reports/tr53/#AMTRA.
 */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { ARABIC_MCM, loadJoiningData } from "./shaping-reference-unicode.mjs";

const args = process.argv.slice(2);
assert.equal(args.filter((arg) => ["--write", "--check"].includes(arg)).length, 1, "Specify --write or --check");
for (let i = 0; i < args.length; i++) {
    if (args[i] === "--source-dir") {
        assert.ok(args[i + 1], "Missing --source-dir");
        process.env.LITE_UNICODE_CACHE = args[++i];
    } else {
        assert.ok(["--write", "--check"].includes(args[i]), `Unknown argument ${args[i]}`);
    }
}
const data = loadJoiningData();
function ranges(property) {
    const result = [];
    for (let scalar = 0; scalar <= 0x10ffff;) {
        const value = property(scalar);
        let end = scalar;
        while (end < 0x10ffff && property(end + 1) === value) {
            end++;
        }
        if (value !== 0) {
            result.push(scalar, end, value);
        }
        scalar = end + 1;
    }
    return result;
}
const typeCodes = { U: 0, R: 1, D: 2, L: 3, T: 4 };
const joining = ranges((scalar) => typeCodes[data.joiningType(scalar)]);
const marks = ranges((scalar) => data.markClass(scalar) | (data.isMcm(scalar) ? 256 : 0));
const digest = createHash("sha256")
    .update(JSON.stringify([joining, marks, ARABIC_MCM]))
    .digest("hex");
const rows = (values) => Array.from({ length: Math.ceil(values.length / 12) }, (_, i) => `    ${values.slice(i * 12, i * 12 + 12).join(", ")},`).join("\n");
const source = `/** Generated by node scripts/generate-arabic-joining-table.mjs --write. DO NOT EDIT.
 * Unicode 16.0.0 / Unicode License v3. Sources and SHA-256:
${Object.entries(data.identities.sources)
    .map(([name, entry]) => ` * ${name}: ${entry.url}\n * ${entry.sha256}`)
    .join("\n")}
 * Arabic modified CCC convention: HarfBuzz 11.0.1 hb-unicode.hh (MIT, HarfBuzz authors).
 * MCM list: Unicode UTR #53 https://www.unicode.org/reports/tr53/#AMTRA.
 * All-scalar Joining_Type cross-check: ${data.identities.crossCheckedScalars} scalars.
 * Deferred font fallback and wider conformance: docs/lite/architecture/compute-text-follow-ups.md CTF-01/02.
 */
export const ARABIC_TABLE_SHA256 = "${digest}";
export const ARABIC_JOINING_RANGES = /* @__PURE__ */ new Uint32Array([
${rows(joining)}
]);
export const ARABIC_MARK_RANGES = /* @__PURE__ */ new Uint32Array([
${rows(marks)}
]);
export const ARABIC_MCM_SCALARS = /* @__PURE__ */ new Uint32Array([${ARABIC_MCM.join(", ")}]);
`;
const output = fileURLToPath(new URL("../packages/babylon-lite/src/text/compute-text-arabic-joining.ts", import.meta.url));
const formatted = await format(source, { parser: "typescript", tabWidth: 4, printWidth: 180, trailingComma: "es5" });
if (args.includes("--write")) {
    writeFileSync(output, formatted);
} else {
    assert.equal(readFileSync(output, "utf8"), formatted, "Arabic property table drift");
}
console.warn(`Arabic Unicode table ${args.includes("--write") ? "written" : "verified"}: ${(joining.length + marks.length + ARABIC_MCM.length) * 4} data bytes; SHA ${digest}`);
